/**
Tests for the argument-binding algorithm generated by the `#[signature(...)]` macro
(defined in the `signature` crate, see `signature/src/lib.rs` and
`signature/src/signature.rs`). That macro generates the `parse()` method used by every
builtin command in this codebase, but has no tests of its own -- a proc-macro crate can
only export macros, so anything that actually *uses* `#[signature(...)]` has to live in a
crate that depends on it, which in practice means here.

These tests construct minimal signature structs and feed them hand-built `Vec<Argument>`
inputs directly, bypassing the parser entirely -- the same approach `src/lang/argument.rs`
already uses for a handful of signature tests (allowed values, `Option`, `#[default(...)]`,
`Vec` collection, `#[named]` collection). This file goes further, specifically targeting
the binding *order* rules: how named vs. unnamed arguments interact, and in particular how
an `#[unnamed()]` collector field (a `Vec<T>` that greedily consumes every remaining
unnamed argument) affects fields declared before and after it in the struct -- a subtlety
that had no coverage at all before this file.

Per instruction, this file only adds tests -- no production code changes, even where a
test below turned up something surprising.
*/

use crate::lang::argument::Argument;
use crate::lang::ast::source::{Source, SourceType};
use crate::lang::errors::CrushResult;
use crate::lang::ordered_string_map::OrderedStringMap;
use crate::lang::state::contexts::CommandContext;
use crate::lang::value::Value;
use signature::signature;
use std::sync::Arc;

fn dummy(_context: CommandContext) -> CrushResult<()> {
    Ok(())
}

fn src() -> Source {
    Source::new(SourceType::Input, Arc::from(""))
}

fn unnamed(value: Value) -> Argument {
    Argument::unnamed(value, &src())
}

fn named(name: &str, value: Value) -> Argument {
    Argument::named(name, value, &src())
}

// ---------------------------------------------------------------------------
// Baseline: positional binding order and named/unnamed interaction, matching what
// docs/language_reference.md documents: "First, all named arguments are assigned.
// Then, each unnamed argument is assigned to the first parameter that doesn't
// already have a value."
// ---------------------------------------------------------------------------

#[signature(dummy)]
struct TwoScalars {
    a: i128,
    b: String,
}

#[test]
fn unnamed_args_bind_in_declaration_order() {
    let (printer, _) = crate::lang::printer::init(None);
    let parsed = TwoScalars::parse(
        vec![unnamed(Value::Integer(1)), unnamed(Value::from("x"))],
        &printer,
    )
    .unwrap();
    assert_eq!(parsed.a, 1);
    assert_eq!(parsed.b, "x");
}

#[test]
fn named_argument_fills_its_slot_so_unnamed_fills_what_remains() {
    let (printer, _) = crate::lang::printer::init(None);
    let parsed = TwoScalars::parse(
        vec![named("b", Value::from("named-b")), unnamed(Value::Integer(7))],
        &printer,
    )
    .unwrap();
    assert_eq!(parsed.a, 7);
    assert_eq!(parsed.b, "named-b");
}

#[signature(dummy)]
struct ThreeScalars {
    a: i128,
    b: i128,
    c: i128,
}

#[test]
fn unnamed_args_skip_slots_already_filled_by_name() {
    let (printer, _) = crate::lang::printer::init(None);
    let parsed = ThreeScalars::parse(
        vec![
            named("b", Value::Integer(20)),
            unnamed(Value::Integer(1)),
            unnamed(Value::Integer(3)),
        ],
        &printer,
    )
    .unwrap();
    assert_eq!(parsed.a, 1);
    assert_eq!(parsed.b, 20);
    assert_eq!(parsed.c, 3);
}

#[test]
