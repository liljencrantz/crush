#[signature(dummy)]
struct BoolFlag {
    #[default(false)]
    verbose: bool,
}

#[test]
fn bool_flag_defaults_to_false_and_can_be_named() {
    let (printer, _) = crate::lang::printer::init(None);
    assert_eq!(
        BoolFlag::parse(vec![], &printer).unwrap().verbose,
        false
    );
    assert_eq!(
        BoolFlag::parse(vec![named("verbose", Value::Bool(true))], &printer)
            .unwrap()
            .verbose,
        true
    );
}

// ---------------------------------------------------------------------------
// #[unnamed()] Vec collector: consumes every remaining unnamed argument greedily.
// ---------------------------------------------------------------------------

#[signature(dummy)]
struct LeadThenCollect {
    first: i128,
    #[unnamed()]
    rest: Vec<String>,
}

#[test]
fn unnamed_collector_takes_everything_left_after_earlier_fields() {
    let (printer, _) = crate::lang::printer::init(None);
    let parsed = LeadThenCollect::parse(
        vec![
            unnamed(Value::Integer(1)),
            unnamed(Value::from("a")),
            unnamed(Value::from("b")),
        ],
        &printer,
    )
    .unwrap();
    assert_eq!(parsed.first, 1);
    assert_eq!(parsed.rest, vec!["a".to_string(), "b".to_string()]);
}

#[test]
fn unnamed_collector_can_be_empty() {
    let (printer, _) = crate::lang::printer::init(None);
    let parsed = LeadThenCollect::parse(vec![unnamed(Value::Integer(1))], &printer).unwrap();
    assert_eq!(parsed.first, 1);
    assert!(parsed.rest.is_empty());
}

#[test]
fn unnamed_collector_can_also_be_fed_by_name() {
    let (printer, _) = crate::lang::printer::init(None);
    let parsed = LeadThenCollect::parse(
        vec![
            unnamed(Value::Integer(1)),
            named("rest", Value::from("named-item")),
        ],
        &printer,
    )
    .unwrap();
    assert_eq!(parsed.first, 1);
    assert_eq!(parsed.rest, vec!["named-item".to_string()]);
}

// ---------------------------------------------------------------------------
// A field declared *after* an #[unnamed()] collector. The collector's mutate code is
// emitted first (struct declaration order), and it drains every remaining unnamed
// argument in a `while !_unnamed.is_empty()` loop -- so by the time a later field's own
// binding code runs, nothing positional is left for it. These tests pin down the
// consequence of that: such a field can only ever be supplied by name.
// ---------------------------------------------------------------------------

#[signature(dummy)]
struct CollectThenRequired {
    #[unnamed()]
    items: Vec<i128>,
    label: String,
}

#[test]
fn field_after_unnamed_collector_can_be_set_by_name() {
    let (printer, _) = crate::lang::printer::init(None);
    let parsed = CollectThenRequired::parse(
        vec![
            unnamed(Value::Integer(1)),
            unnamed(Value::Integer(2)),
            named("label", Value::from("x")),
        ],
        &printer,
    )
    .unwrap();
    assert_eq!(parsed.items, vec![1, 2]);
    assert_eq!(parsed.label, "x");
}

#[test]
fn field_after_unnamed_collector_cannot_be_set_positionally() {
    // `label` is declared after `items`, which is the #[unnamed()] collector. Since
    // `items` greedily drains every remaining unnamed value first, `label` never gets a
    // chance to consume one -- it isn't named here either, so this should fail with a
    // clear "no value provided" error rather than silently taking the last positional
    // value as `label`, or leaving it with some bogus/empty value.
    let (printer, _) = crate::lang::printer::init(None);
    let result = CollectThenRequired::parse(
        vec![
            unnamed(Value::Integer(1)),
            unnamed(Value::Integer(2)),
            unnamed(Value::from("x")),
        ],
        &printer,
    );
    assert!(
        result.is_err(),
        "expected an error since `label` was never named and can't be filled \
         positionally after the #[unnamed()] collector"
    );
}

#[signature(dummy)]
struct CollectThenDefaulted {
    #[unnamed()]
    items: Vec<i128>,
    #[default("fallback")]
    label: String,
}

#[test]
fn field_after_unnamed_collector_with_default_falls_back_rather_than_stealing_a_positional_value() {
    // Same shape as CollectThenRequired, but `label` has a default. Does giving it a
    // default let it "reach past" the collector and grab a positional value anyway, or
    // does it just fall back to its default like the required case falls back to an
    // error? (The generated code for a defaulted field after a collector *is* still
    // emitted, unlike the required case -- but the collector has already drained
    // `_unnamed` by the time that code runs, so the expectation here is that it always
    // falls back to the default, never actually consuming a positional value.)
    let (printer, _) = crate::lang::printer::init(None);
    let parsed = CollectThenDefaulted::parse(
        vec![
            unnamed(Value::Integer(1)),
            unnamed(Value::Integer(2)),
            unnamed(Value::Integer(3)),
        ],
        &printer,
    )
    .unwrap();
    assert_eq!(parsed.items, vec![1, 2, 3]);
    assert_eq!(
        parsed.label, "fallback",
        "label should fall back to its default, since the collector already consumed \
         every positional argument before label's own binding code ever runs"
    );
}

#[test]
fn field_after_unnamed_collector_with_default_can_still_be_set_by_name() {
    let (printer, _) = crate::lang::printer::init(None);
    let parsed = CollectThenDefaulted::parse(
        vec![unnamed(Value::Integer(1)), named("label", Value::from("explicit"))],
        &printer,
    )
    .unwrap();
    assert_eq!(parsed.items, vec![1]);
    assert_eq!(parsed.label, "explicit");
}

// ---------------------------------------------------------------------------
// #[named()] collector (OrderedStringMap<T>) does *not* set the same flag an
// #[unnamed()] collector does, so a field declared after it can still bind positionally.
// This mirrors the real shape of control::for's `For` struct (`#[named()] iterator:
// OrderedStringMap<Value>` followed by a plain positional `body: Command`), which relies
// on exactly this behavior in production.
// ---------------------------------------------------------------------------

#[signature(dummy)]
struct NamedCollectorThenPositional {
    #[named()]
    extra: OrderedStringMap<Value>,
    body: String,
}

#[test]
fn field_after_named_collector_can_still_bind_positionally() {
    let (printer, _) = crate::lang::printer::init(None);
    let parsed = NamedCollectorThenPositional::parse(
        vec![named("i", Value::Integer(5)), unnamed(Value::from("the-body"))],
        &printer,
    )
    .unwrap();
    assert_eq!(parsed.body, "the-body");
    let extra = parsed.extra.into_iter().collect::<Vec<_>>();
    assert_eq!(extra.len(), 1);
    assert_eq!(extra[0].0, "i");
    assert!(extra[0].1 == Value::Integer(5));
}

#[test]
fn named_collector_gathers_every_unmatched_named_argument() {
    let (printer, _) = crate::lang::printer::init(None);
    let parsed = NamedCollectorThenPositional::parse(
        vec![
            named("foo", Value::from("a")),
            named("bar", Value::from("b")),
            unnamed(Value::from("body-value")),
        ],
        &printer,
    )
    .unwrap();
    assert_eq!(parsed.body, "body-value");
    let extra = parsed.extra.into_iter().collect::<Vec<_>>();
    assert_eq!(extra.len(), 2);
    assert_eq!(extra[0].0, "foo");
    assert!(extra[0].1 == Value::from("a"));
    assert_eq!(extra[1].0, "bar");
    assert!(extra[1].1 == Value::from("b"));
}

#[test]
fn named_collector_can_be_empty() {
    let (printer, _) = crate::lang::printer::init(None);
    let parsed = NamedCollectorThenPositional::parse(
        vec![unnamed(Value::from("only-body"))],
        &printer,
    )
    .unwrap();
    assert_eq!(parsed.body, "only-body");
    assert!(parsed.extra.into_iter().collect::<Vec<_>>().is_empty());
}
